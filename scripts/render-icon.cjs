const { app, BrowserWindow } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
app.setPath('userData', path.join(root, 'test-results', 'icon-profile'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 256, height: 256, useContentSize: true, transparent: true, webPreferences: { sandbox: true, nodeIntegration: false, contextIsolation: true } })
  const svg = await fs.readFile(path.join(root, 'resources', 'icon.svg'), 'utf8')
  await window.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(`<html><body style="margin:0;overflow:hidden">${svg}</body></html>`))
  await window.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  const image = (await window.webContents.capturePage()).resize({ width: 256, height: 256 })
  const png = image.toPNG()
  const header = Buffer.alloc(22)
  header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4)
  header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12)
  header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18)
  const ico = Buffer.concat([header, png])
  await fs.mkdir(path.join(root, 'src', 'renderer', 'public'), { recursive: true })
  await fs.writeFile(path.join(root, 'resources', 'icon.ico'), ico)
  await fs.writeFile(path.join(root, 'src', 'renderer', 'public', 'icon.ico'), ico)
  console.log('Rendered code-native SVG to Windows icon (' + ico.length + ' bytes)')
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
