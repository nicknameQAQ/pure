async function poll(fn, label) {
  for (let i = 0; i < 160; i++) { if (await fn()) return; await new Promise(resolve => setTimeout(resolve, 80)) }
  throw new Error(`Timed out: ${label}`)
}
async function idle() { await poll(async () => await page.locator('.app').getAttribute('aria-busy') === 'false', 'idle') }
async function query(value) {
  await page.getByRole('textbox', { name: '查找文字', exact: true }).fill(value)
  await page.waitForTimeout(150)
}
async function count(value) { await poll(async () => (await page.locator('.find-count').innerText()).split('/').pop() === String(value), 'find count ' + value) }
async function launch() {
  app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: executablePath ? [] : ['.'], cwd: process.cwd(), env, timeout: 30000 })
  page = await app.firstWindow()
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.show(); win.focus(); win.webContents.focus() })
  await page.bringToFront()
  page.on('pageerror', error => errors.push(error.message))
  await page.locator('.ProseMirror').waitFor()
}
